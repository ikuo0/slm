import numpy as np

# 1. 超低次元（8次元）のシンボルベクトル（+1 と -1 だけで定義）
# 本来は10,000次元でランダム生成すると互いにほぼ直交（内積≒0）します
KEYS = {
    "color": np.array([ 1, -1,  1, -1,  1, -1,  1, -1]),
    "shape": np.array([ 1,  1, -1, -1,  1,  1, -1, -1]),
}

VALUES = {
    "red":    np.array([ 1,  1,  1,  1, -1, -1, -1, -1]),
    "blue":   np.array([-1, -1,  1,  1,  1,  1, -1, -1]),
    "circle": np.array([ 1, -1, -1,  1,  1, -1, -1,  1]),
    "square": np.array([-1,  1,  1, -1, -1,  1,  1, -1]),
}

def similarity(v1, v2):
    """コサイン類似度（内積 / 次元数）: 1.0なら完全一致、0.0なら無関係"""
    return np.dot(v1, v2) / len(v1)

# --------------------------------------------------
# 操作1: バインド（紐付け = 要素ごとの掛け算）
# 「キー」と「値」を掛け合わせて、属性ペアを作る
# --------------------------------------------------
pair_color = KEYS["color"] * VALUES["red"]     # color: red
pair_shape = KEYS["shape"] * VALUES["circle"]  # shape: circle

# --------------------------------------------------
# 操作2: バンドル（束ねる = 要素ごとの足し算）
# 2つの属性ペアを足して、1本の「オブジェクト」に圧縮する
# --------------------------------------------------
obj = pair_color + pair_shape

print("=== 圧縮された1本のベクトル ===")
print("Object Vector:", obj)
# 出力例: [ 2  0  0  0  2  0  0  0] のような整数ベクトルにまとまる


# --------------------------------------------------
# クエリ1: 「このオブジェクトに color: red は含まれるか？」
# --------------------------------------------------
sim_red = similarity(obj, pair_color)
sim_fake = similarity(obj, KEYS["color"] * VALUES["blue"]) # 含まれていないペア

print("\n=== 類似度検索 ===")
print(f"color: red のマッチ度   : {sim_red:.2f}")   # 高い正の値が出る
print(f"color: blue のマッチ度  : {sim_fake:.2f}")  # 0付近（直交）になる


# --------------------------------------------------
# クエリ2: 「color の値を取り出す（アンバインド）」
# HDCの魔法: 同じキーベクトルをもう一度掛けるとキーが消滅する！
# (+1)^2 = 1, (-1)^2 = 1 なので、KEYS["color"] * KEYS["color"] = 全て1になるため
# --------------------------------------------------
recovered = obj * KEYS["color"]

print("\n=== 値の復元（キーによるアンバインド） ===")
# 復元されたベクトルと、各候補シンボルとの類似度を比較（辞書引き）
for name, vec in VALUES.items():
    score = similarity(recovered, vec)
    print(f"候補 '{name:<6}' との類似度: {score:.2f}")


